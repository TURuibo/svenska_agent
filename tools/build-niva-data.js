#!/usr/bin/env node
// Build the 🪜 Nivå data: site/niva/niva-data.js → window.NIVA_DATA.
//
// Nivå (site/niva/) shows everything at one CEFR level on one page — grammar, words,
// phrases, reading texts, scenarios, listening, textbook lessons — in a fixed order.
// The page must open fast on a phone, so it loads only this file, not the 6 MB
// kb-index.js. Contract (frozen): site/niva/SPEC.md §10. Level rules: tools/level-lib.js.
//
// Inputs:
//   knowledge_base/{words,phrases,sentences,grammar,topics}/*.md   read directly
//   imported/*.md                                                    grammar link counts
//   listening/*.json                                                 episodes
//   site/reading/reading-data.js   texts with lv / lvHi / d / lix … ← node tools/build-reading-site.js
//
// Gitignored; generated by the GitHub Action (kb-site.yml) after build-reading-site.js.
// Output is deterministic for the same inputs (`generatedAt` is the only clock value).
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const LV = require('./level-lib');

const repoRoot = path.resolve(__dirname, '..');
const kbDir = path.join(repoRoot, 'knowledge_base');
const importedDir = path.join(repoRoot, 'imported');
const listenDir = path.join(repoRoot, 'listening');
const readingPath = path.join(repoRoot, 'site', 'reading', 'reading-data.js');
const outPath = path.join(repoRoot, 'site', 'niva', 'niva-data.js');
const MAX_BYTES = 1000000;   // SPEC §10 budget; going over only warns (never fail the site build)

// ---------------------------------------------------------------- helpers
const CJK = /[㐀-鿿]/;
const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
function clean(s) {
  return String(s == null ? '' : s)
    .replace(/\[\[([^\]|]*)\|([^\]]*)\]\]/g, '$2')
    .replace(/\[\[([^\]]*)\]\]/g, '$1')
    .replace(/[`*]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}
function cut(s, n) {
  const t = String(s || '');
  return t.length <= n ? t : t.slice(0, n - 1).replace(/[\s,;:，；、–—-]+$/, '') + '…';
}
const listOf = (v) => (Array.isArray(v) ? v : v ? [v] : []).map((x) => String(x).trim()).filter(Boolean);

// Flat YAML frontmatter with inline [a, b] lists and indented "- item" lists.
function parseNote(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  const fm = {};
  if (!m) return { fm, body: text };
  const lines = m[1].split(/\r?\n/);
  for (let i = 0; i < lines.length; i += 1) {
    const km = lines[i].match(/^([^\s:#][^:]*):\s*(.*)$/);
    if (!km) continue;
    const key = km[1].trim();
    let rest = km[2].replace(/\s+#.*$/, '').trim();
    if (rest === '') {
      const items = [];
      while (i + 1 < lines.length && /^\s+-\s+/.test(lines[i + 1])) {
        i += 1;
        items.push(lines[i].replace(/^\s+-\s+/, '').trim().replace(/^['"]|['"]$/g, ''));
      }
      fm[key] = items.length ? items : '';
      continue;
    }
    const list = rest.match(/^\[(.*)\]$/);
    if (list) fm[key] = list[1].split(',').map((x) => x.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean);
    else fm[key] = rest.replace(/^['"]|['"]$/g, '');
  }
  return { fm, body: m[2] };
}

function readFolder(name) {
  const dir = path.join(kbDir, name);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort().map((f) => {
    const text = fs.readFileSync(path.join(dir, f), 'utf8');
    return { slug: f.slice(0, -3), text, ...parseNote(text) };
  });
}

// ---------------------------------------------------------------- inputs
if (!fs.existsSync(readingPath)) {
  console.error('Missing site/reading/reading-data.js — run `node tools/build-reading-site.js` first.');
  process.exit(1);
}
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(readingPath, 'utf8'), sandbox, { filename: 'reading-data.js' });
const articles = ((sandbox.window.READING_DATA && sandbox.window.READING_DATA.articles) || [])
  .filter((a) => a.status === 'imported');

const words = readFolder('words');
const phrases = readFolder('phrases');
const sentences = readFolder('sentences');
const grammar = readFolder('grammar');
const topics = readFolder('topics');

let reference = [];
try { reference = JSON.parse(fs.readFileSync(path.join(repoRoot, 'profile', 'vocab-gaps.json'), 'utf8')).reference || []; } catch (_e) { /* optional */ }
const kellyRank = new Map();
for (const e of reference) {
  if (e.s !== 'k' || !e.r) continue;
  for (const w of [e.w, e.g]) {
    const k = String(w || '').toLowerCase();
    if (k && (!kellyRank.has(k) || e.r < kellyRank.get(k))) kellyRank.set(k, e.r);
  }
}

const topicZh = new Map(topics.map((t) => [t.slug, clean(t.fm.zh || t.fm.name || t.slug)]));

// ---------------------------------------------------------------- words
const wordRank = new Map();   // slug and lemma (lowercase) → level rank, for phrase inference
const wordRows = [];
for (const n of words) {
  const fm = n.fm;
  const lemma = clean(fm.lemma || n.slug);
  const place = LV.placement(LV.parseLevel(fm.cefr));
  const r = LV.rankOf(place.lv);
  if (r) { wordRank.set(n.slug, r); wordRank.set(lemma.toLowerCase(), r); }
  const p = String(fm.ordklass || '').toLowerCase().split(/[\s/(,.]/)[0] || '';
  let g = '';
  if (/^sub/.test(p)) {
    g = /^(en|ett)$/.test(String(fm.genus || '')) ? fm.genus : ((/^#[^\n]*?\((en|ett)\)/m.exec(n.body) || [])[1] || '');
  }
  // en / ipa / forms are for P1's flip-card review and will live in lazily loaded
  // per-level files (SPEC §10) — the list view only needs the gloss.
  wordRows.push({
    s: n.slug,
    l: lemma,
    p,
    g,
    zh: cut(clean(fm.zh), 36),
    lv: place.lv,
    br: place.br,
    tp: listOf(fm.topics).find((t) => topicZh.has(t)) || '',
    fq: kellyRank.get(lemma.toLowerCase()) || 0,
    k: fm.known === 'true' || fm.known === true ? 1 : 0,
  });
}

// ---------------------------------------------------------------- sentences (counts + levels for phrase inference)
const sentRank = new Map();
const sentenceCounts = { A1: 0, A2: 0, B1: 0, B2: 0 };
const phrasesOfSentence = new Map();
for (const n of sentences) {
  const place = LV.placement(LV.parseLevel(n.fm.cefr));
  if (place.lv) { sentenceCounts[place.lv] += 1; sentRank.set(n.slug, LV.rankOf(place.lv)); }
  for (const ph of listOf(n.fm.phrases)) {
    if (!phrasesOfSentence.has(ph)) phrasesOfSentence.set(ph, []);
    phrasesOfSentence.get(ph).push(n.slug);
  }
}

// ---------------------------------------------------------------- phrases
// Category spellings vary a lot (fast-uttryck, situationsfras, 动词搭配 …) — fold them
// into a handful of display groups; the page labels them.
function phraseGroup(cat) {
  const c = String(cat || '').toLowerCase();
  if (/partikel/.test(c)) return 'partikel';
  if (/idiom|习语|ordspr/.test(c)) return 'idiom';
  if (/preposition|介词/.test(c)) return 'prep';
  if (/^tid|tids|时间|频率/.test(c)) return 'tid';
  if (/diskurs|konnektiv|konjunktion|subjunktion|连接|论说/.test(c)) return 'diskurs';
  if (/^verb|verbfras|动词|kollokation|collocation|搭配|reflexiv|反身/.test(c)) return 'verb';
  if (/fras|hälsning|artighet|avsked|avslut|tröst|fråga|frågefras|uppmaning|svar|service|ursäkt|samtycke|turtagning|礼貌|问句|道歉|祝愿|安慰|语|短语/.test(c)) return 'fras';
  if (/uttryck|fast|固定|konstruktion|struktur|pattern|句式|表达/.test(c)) return 'fast';
  return 'ovrigt';
}
const phraseRows = [];
let phrasesUnplaced = 0;
for (const n of phrases) {
  const fm = n.fm;
  let place = LV.placement(LV.parseLevel(fm.cefr));
  let inf = 0;
  if (!place.lv) {
    // ≈ the hardest of its head words; else the median level of the sentences it occurs in.
    const heads = listOf(fm.head_words).map((h) => wordRank.get(h) || wordRank.get(h.toLowerCase()) || 0).filter(Boolean);
    let lv = heads.length ? LV.levelFromRank(Math.max(...heads)) : '';
    if (!lv) {
      const sl = [...new Set([...listOf(fm.sentences), ...(phrasesOfSentence.get(n.slug) || [])])];
      lv = LV.medianLevel(sl.map((s) => sentRank.get(s) || 0));
    }
    if (lv) { place = { lv, hi: '', br: 0 }; inf = 1; }
  }
  if (!place.lv) { phrasesUnplaced += 1; continue; }
  phraseRows.push({
    s: n.slug,
    sv: clean(fm.phrase || n.slug),
    cat: phraseGroup(fm.category),
    zh: cut(clean(fm.zh), 36),
    lv: place.lv,
    br: place.br,
    inf,
    k: fm.known === 'true' || fm.known === true ? 1 : 0,
  });
}

// ---------------------------------------------------------------- grammar
// Order inside a level = how many notes / articles link to the point (more = more common
// = learn first). Top third → tier 1 核心, middle → 2 常用, rest → 3 细节.
const linkCount = new Map();
function countLinks(text, self) {
  const seen = new Set();
  const re = /\[\[(grammar-[^\]|#]+)/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    const t = m[1].trim();
    if (t !== self) seen.add(t);
  }
  for (const t of seen) linkCount.set(t, (linkCount.get(t) || 0) + 1);
}
for (const n of [...words, ...phrases, ...sentences, ...grammar, ...topics]) countLinks(n.text, n.slug);
for (const f of fs.existsSync(kbDir + '/sources') ? fs.readdirSync(path.join(kbDir, 'sources')) : []) {
  if (f.endsWith('.md')) countLinks(fs.readFileSync(path.join(kbDir, 'sources', f), 'utf8'), f.slice(0, -3));
}
for (const f of fs.existsSync(importedDir) ? fs.readdirSync(importedDir) : []) {
  if (f.endsWith('.md')) countLinks(fs.readFileSync(path.join(importedDir, f), 'utf8'), '');
}

const grammarRows = [];
for (const n of grammar) {
  const fm = n.fm;
  const line = (n.body.match(/^级别[:：]\s*(.+)$/m) || [])[1];
  const p = LV.parseLevel(fm.cefr) || LV.parseLevel(fm.level) || LV.parseLevel(line);
  const place = LV.placement(p);
  if (!place.lv) continue;
  const one = (n.body.match(/^一句话[:：]\s*(.+)$/m) || [])[1] || '';
  grammarRows.push({
    s: n.slug,
    n: clean(fm.name || n.slug.replace(/^grammar-/, '')),
    zh: cut(clean(fm.zh), 40),
    one: cut(clean(one), 120),
    lv: place.lv,
    br: place.br,
    inf: 0,
    links: linkCount.get(n.slug) || 0,
    tier: 0,
    ord: 0,
  });
}
for (const lv of LV.LEVELS) {
  for (const br of [0, 1]) {
    const list = grammarRows.filter((g) => g.lv === lv && g.br === br)
      .sort((a, b) => b.links - a.links || cmp(a.s, b.s));
    list.forEach((g, i) => {
      g.ord = i + 1;
      g.tier = br ? 0 : 1 + Math.min(2, Math.floor((i * 3) / list.length));
    });
  }
}
grammarRows.sort((a, b) => cmp(LV.rankOf(a.lv), LV.rankOf(b.lv)) || a.br - b.br || a.ord - b.ord);
for (const g of grammarRows) delete g.links;

// ---------------------------------------------------------------- texts · lessons · listening
function cleanTitle(t) {
  return String(t || '')
    .replace(/^[\s\u{1F1E6}-\u{1F1FF}\u{1F3A7}\u{1F4F0}\u{1F4D6}]+/u, '')
    .replace(/\s*[（(][^()（）]*[\/／][^()（）]*[)）]\s*$/u, '')
    .trim();
}
const FORM_TAG = { dialog: '对话', text: '文本', story: '故事' };
const KURS_MARK = /^##\s+🔍\s*逐段精读/m;
const horningByDate = new Map();
const texts = [];
const kurs = [];
for (const a of articles) {
  if (!a.lv) continue;
  if (a.slug.startsWith('horning-')) { horningByDate.set((a.slug.match(/\d{4}-\d{2}-\d{2}/) || [''])[0], a.slug); continue; }
  const base = { s: a.slug, t: cleanTitle(a.title), lv: a.lv, br: a.lvHi ? 1 : 0, inf: a.lvInf ? 1 : 0, date: a.date || '' };
  if (KURS_MARK.test(a.body || '')) {
    kurs.push({ ...base, paras: ((a.body || '').match(/^###\s*¶\s*\d+/gm) || []).length });
    continue;
  }
  const tala = a.kind === 'scenario';
  texts.push({
    ...base,
    page: tala ? 'tala' : 'reading',
    kind: a.kind,
    tag: tala ? (FORM_TAG[a.form] || '情景') : (a.kind === 'adjsubst' ? '词形练习' : (a.genre || (a.kindLabel && a.kindLabel.zh) || '')),
    d: a.d || 0,
    lix: a.lix || 0,
    n: a.n || 0,
    over: a.over == null ? -1 : a.over,
    up: a.up ? 1 : 0,
    dialog: a.dialog ? 1 : 0,
  });
}
// Easiest first: difficulty bucket, then above-level share, then LIX; texts without a
// measurement (drill pages) after the measured ones.
texts.sort((a, b) => cmp(LV.rankOf(a.lv), LV.rankOf(b.lv)) || cmp(a.page, b.page) || a.br - b.br ||
  (a.d ? 0 : 1) - (b.d ? 0 : 1) || a.d - b.d || a.over - b.over || a.lix - b.lix || cmp(a.s, b.s));
kurs.sort((a, b) => cmp(LV.rankOf(a.lv), LV.rankOf(b.lv)) || a.br - b.br || cmp(a.date, b.date) || cmp(a.s, b.s));

const listen = [];
for (const f of fs.existsSync(listenDir) ? fs.readdirSync(listenDir).sort() : []) {
  if (!f.endsWith('.json') || f.startsWith('_')) continue;
  let ep;
  try { ep = JSON.parse(fs.readFileSync(path.join(listenDir, f), 'utf8')); } catch (err) { console.error(`(skipping listening/${f}: ${err.message})`); continue; }
  const id = ep.id || f.replace(/\.json$/, '');
  const linked = ep.readingSlug ? articles.find((a) => a.slug === ep.readingSlug) : null;
  const place = LV.placement(LV.parseLevel(ep.cefr) || (linked ? LV.parseLevel(linked.lvHi ? `${linked.lv}–${linked.lvHi}` : linked.lv) : null));
  if (!place.lv) continue;
  const date = ep.date || (f.match(/\d{4}-\d{2}-\d{2}/) || [''])[0];
  // SVT episodes (svt-latt-<date>.json, id = SVT's video id) have their transcript as an
  // imported/horning-<date>.md article; textbook audio names its article in readingSlug.
  const reading = ep.readingSlug || (f.startsWith('svt-latt-') ? horningByDate.get(date) || '' : '');
  listen.push({
    id,
    t: cleanTitle(ep.title || id),
    src: clean(ep.source || ''),
    lv: place.lv,
    br: place.br,
    dur: Math.round(Number(ep.duration) || 0),
    cues: Array.isArray(ep.cues) ? ep.cues.length : 0,
    date,
    reading,
  });
}
listen.sort((a, b) => cmp(LV.rankOf(a.lv), LV.rankOf(b.lv)) || a.br - b.br || (b.cues ? 1 : 0) - (a.cues ? 1 : 0) || cmp(a.date, b.date) || cmp(a.id, b.id));

// ---------------------------------------------------------------- write
const usedTopics = {};
for (const w of wordRows) if (w.tp) usedTopics[w.tp] = topicZh.get(w.tp);

const data = {
  v: 1,
  generatedAt: process.env.KB_SITE_GENERATED_AT || new Date().toISOString(),
  levels: [
    { id: 'A1', sfi: 'SFI A', name: '入门', can: '靠帮助应付最具体的日常：问候、介绍自己、填写个人信息' },
    { id: 'A2', sfi: 'SFI B', name: '基础', can: '应付日常常见场景：写短消息，讲自己的经历和熟悉的人、地方', bridge: 'SFI C' },
    { id: 'B1', sfi: 'SFI D', name: '进阶', can: '应付较正式的场景：读写说明文和论述文，用简单论据回应别人的观点' },
    { id: 'B2', sfi: 'Gy SVA nivå 1', name: '中高级', can: '口头演讲，多种文体，读非虚构作品和文学' },
  ],
  grammar: grammarRows,
  words: wordRows.filter((w) => w.lv).sort((a, b) => cmp(LV.rankOf(a.lv), LV.rankOf(b.lv)) || cmp(a.s, b.s)),
  phrases: phraseRows.sort((a, b) => cmp(LV.rankOf(a.lv), LV.rankOf(b.lv)) || cmp(a.s, b.s)),
  phrasesUnplaced,
  sentences: sentenceCounts,
  texts,
  listen,
  kurs,
  topics: usedTopics,
};

const js = `window.NIVA_DATA = ${JSON.stringify(data)};\n`;
const bytes = Buffer.byteLength(js, 'utf8');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, js, 'utf8');

const per = (rows) => LV.LEVELS.map((lv) => rows.filter((r) => r.lv === lv).length).join('/');
console.log(`Generated ${path.relative(repoRoot, outPath)} (${(bytes / 1024).toFixed(0)} KB) — A1/A2/B1/B2: ` +
  `grammar ${per(grammarRows)} · words ${per(data.words)} · phrases ${per(phraseRows)} (+${phrasesUnplaced} unplaced) · ` +
  `reading ${per(texts.filter((t) => t.page === 'reading'))} · tala ${per(texts.filter((t) => t.page === 'tala'))} · ` +
  `listen ${per(listen)} · kurs ${per(kurs)}`);
if (bytes > MAX_BYTES) {
  console.warn(`⚠️ niva-data.js is ${bytes} bytes — over the ${MAX_BYTES}-byte budget (SPEC §10). The page still works; trim fields or split per level.`);
}
