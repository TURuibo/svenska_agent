const CJK = /[㐀-鿿]/;
const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
function clean(s) {
  return String(s == null ? '' : s)
    .replace(/\[\[([^\]|]*)\|([^\]]*)\]\]/g, '$2')
    .replace(/\[\[([^\]]*)\]\]/g, '$1')
    .replace(/[`*]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}
function cut(s, n) {
  const t = String(s || '');
  return t.length <= n ? t : t.slice(0, n - 1).replace(/[\s,;:，；、–—-]+$/, '') + '…';
}
const listOf = (v) => (Array.isArray(v) ? v : v ? [v] : []).map((x) => String(x).trim()).filter(Boolean);

// Flat YAML frontmatter with inline [a, b] lists and indented "- item" lists.
function parseNote(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  const fm = {};
  if (!m) return { fm, body: text };
  const lines = m[1].split(/\r?\n/);
  for (let i = 0; i < lines.length; i += 1) {
    const km = lines[i].match(/^([^\s:#][^:]*):\s*(.*)$/);
    if (!km) continue;
    const key = km[1].trim();
    let rest = km[2].replace(/\s+#.*$/, '').trim();
    if (rest === '') {
      const items = [];
      while (i + 1 < lines.length && /^\s+-\s+/.test(lines[i + 1])) {
        i += 1;
        items.push(lines[i].replace(/^\s+-\s+/, '').trim().replace(/^['"]|['"]$/g, ''));
      }
      fm[key] = items.length ? items : '';
      continue;
    }
    const list = rest.match(/^\[(.*)\]$/);
    if (list) fm[key] = list[1].split(',').map((x) => x.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean);
    else fm[key] = rest.replace(/^['"]|['"]$/g, '');
  }
  return { fm, body: m[2] };
}

function readFolder(name) {
  const dir = path.join(kbDir, name);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort().map((f) => {
    const text = fs.readFileSync(path.join(dir, f), 'utf8');
    return { slug: f.slice(0, -3), text, ...parseNote(text) };
  });
}

