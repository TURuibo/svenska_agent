// ---------------------------------------------------------------- text helpers
const CJK = /[㐀-鿿]/;
const ISO = /^\d{4}-\d{2}-\d{2}$/;

function clean(s) {
  return String(s == null ? '' : s)
    .replace(/\[\[([^\]|]*)\|([^\]]*)\]\]/g, '$2')
    .replace(/\[\[([^\]]*)\]\]/g, '$1')
    .replace(/`/g, '')
    .replace(/\*\*/g, '')
    .replace(/(^|[\s(（])\*([^*\s][^*]*?)\*(?=[\s).,;:!?，。）]|$)/g, '$1$2')
    .replace(/^[\s\u{1F1E6}-\u{1F1FF}✅❌✔✖️\u{1F4CC}\u{1F4D0}⚠]+/u, '')
    .replace(/\s+/g, ' ')
    .trim();
}
function cut(s, n) {
  const t = String(s || '');
  if (t.length <= n) return t;
  const sp = t.lastIndexOf(' ', n - 1);
  return t.slice(0, sp > n * 0.6 ? sp : n - 1).replace(/[\s,;:–—-]+$/, '') + '…';
}
function fold(s) {
  return String(s || '').toLowerCase().normalize('NFC').replace(/\s+/g, ' ').trim();
}
function dateInSlug(slug) {
  const m = /(\d{4}-\d{2}-\d{2})/.exec(String(slug || ''));
  return m ? m[1] : '';
}
function dayNum(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  return Math.round(Date.UTC(y, m - 1, d) / 86400000);
}
const bodyOf = (slug) => (bodies[slug] && bodies[slug].body) || '';
const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// Sentence splitting for the Swedish text (approximate: ". " followed by a capital / dash / quote).
function svSentences(text) {
  return String(text).split(/(?<=[.!?…])\s+(?=[A-ZÅÄÖÉ0-9–—"“(])/).map((s) => s.trim()).filter(Boolean);
}
function zhSentences(text) {
  return String(text).split(/(?<=[。！？!?](?:[”’"」』）)])?)\s*/).map((s) => s.trim()).filter(Boolean);
}
// Cut Swedish text at a sentence boundary <= max chars; returns { text, kept, total }.
function fitSv(text, max) {
  const ss = svSentences(text);
  let out = '';
  let kept = 0;
  for (const s of ss) {
    const next = out ? `${out} ${s}` : s;
    if (next.length > max) break;
    out = next;
    kept += 1;
  }
  if (!kept) return { text: cut(ss[0] || text, max), kept: 0, total: ss.length };
  return { text: out, kept, total: ss.length };
}
// Chinese counterpart of a (possibly truncated) Swedish text. `dropFirst` removes a leading
// translated-title sentence (the 8 Sidor news format always starts its 🇨🇳 line with one).
// Untruncated text keeps the whole translation; a truncated one is only aligned when the
// Chinese and Swedish sentence counts agree, otherwise ''.
function alignZh(zhText, fit, dropFirst) {
  if (!zhText) return '';
  const zs = zhSentences(zhText);
  const body = dropFirst ? zs.slice(1) : zs;
  if (!body.length) return '';
  if (fit.kept === fit.total) return body.join('');
  if (!fit.kept || body.length !== fit.total) return '';
  return body.slice(0, fit.kept).join('');
}

// "🇸🇪 SV — 🇨🇳 ZH" example pairs from a note body (inline, or zh on the following line).
function examplePairs(body) {
  const lines = String(body).split('\n');
  const pairs = [];
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    if (!line.includes('🇸🇪') || /Förklaring/.test(line) || /^\s*\|/.test(line)) continue;
    if (/❌/.test(line)) continue;
    let rest = line.slice(line.lastIndexOf('🇸🇪') + '🇸🇪'.length);
    let sv;
    let zh;
    const k = rest.indexOf('🇨🇳');
    if (k >= 0) {
      sv = rest.slice(0, k);
      zh = rest.slice(k + '🇨🇳'.length);
    } else {
      const nx = (lines[i + 1] || '').trim();
      if (!nx.startsWith('🇨🇳')) continue;
      sv = rest;
      zh = nx.slice('🇨🇳'.length);
    }
    sv = clean(sv.replace(/[\s—–-]+$/, ''));
    zh = clean(zh);
    if (!sv || !zh || CJK.test(sv) || !CJK.test(zh) || !/[A-Za-zÅÄÖåäö]{2}/.test(sv)) continue;
    pairs.push([sv, zh]);
  }
  return pairs;
}

