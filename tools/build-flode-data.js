// Grammar is parameter-free; compute once (also fills the grammar coverage counters).
const grammar = buildGrammar();

function assemble(P) {
  const sentences = buildSentences(P);
  const covered = new Set(sentences.flatMap((x) => x.w));
  const { out: words, topicsUsed } = buildWords(P, covered);
  const phrases = buildPhrases(P);
  const { latest, bites, fresh, recent } = buildArticlesAndBites(P, new Set(sentences.map((x) => x.s)));
  const topics = {};
  for (const t of [...topicsUsed].sort()) topics[t] = topicZh.get(t);
  const data = {
    v: 1,
    generatedAt: process.env.KB_SITE_GENERATED_AT || new Date().toISOString(),
    latest,
    words,
    sentences,
    phrases,
    grammar,
    bites,
    fresh,
    recent,
    topics,
  };
  return `window.FLODE_DATA = ${JSON.stringify(data)};\n`;
}

