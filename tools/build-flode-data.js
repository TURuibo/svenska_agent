function loadInputs() {
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  for (const input of INPUTS) {
    const p = path.join(siteRoot, input.file);
    if (!fs.existsSync(p)) {
      console.error(`Missing site/${input.file} — run \`${input.builder}\` first ` +
        '(full chain: node tools/build-kb-site.js && node tools/vocab-progress.js && node tools/build-reading-site.js).');
      process.exit(1);
    }
    vm.runInContext(fs.readFileSync(p, 'utf8'), sandbox, { filename: input.file });
  }
  return sandbox.window;
}

