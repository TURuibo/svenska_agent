#!/usr/bin/env node
// Build the Flöde card-feed data: site/flode/flode-data.js -> window.FLODE_DATA.
//
// Flöde (site/flode/, 🌊) slices the knowledge base into 5–20 second cards
// (word / quiz / cloze / en-ett / sentence / listen / phrase / grammar / news /
// dialog / teaser / pairs). The page must open fast on a phone, so it does NOT
// load the multi-MB viewer data — this script distils the parts it needs into
// one small file (budget: <= 3.2 MB raw). The shape is the frozen contract in
// site/flode/SPEC.md §6; do not rename fields.
//
// Input is the OTHER builders' output (run them first, as the GitHub Action does):
//   site/kb-index.js + site/kb-bodies.js   ← tools/build-kb-site.js
//   site/reading/reading-data.js           ← tools/build-reading-site.js
//   site/vocab-progress.js                 ← tools/vocab-progress.js
// Word `genus` is read from the note frontmatter (knowledge_base/words/*.md) because
// the index does not carry it; the header "# lemma — substantiv (en)" is the fallback.
//
// Output is deterministic for the same inputs (stable sorts; `generatedAt` is the only
// clock value). Gitignored; generated by the GitHub Action (kb-site.yml).
