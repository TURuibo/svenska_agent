const sentBySlug = new Map(sentNotes.map((n) => [n.slug, n]));
const sentText = (n) => clean(n.sentence || String(n.title || '').replace(/^🇸🇪\s*/, ''));

// lemma / slug / unique-surface-form -> word slug
const wordByKey = new Map();
const formOwners = new Map();
for (const n of wordNotes) {
  wordByKey.set(fold(n.slug), n.slug);
  wordByKey.set(fold(n.lemma || n.title), n.slug);
  for (const f of n.forms || []) {
    const k = fold(f);
    if (!formOwners.has(k)) formOwners.set(k, new Set());
    formOwners.get(k).add(n.slug);
  }
}
for (const [k, owners] of formOwners) if (owners.size === 1 && !wordByKey.has(k)) wordByKey.set(k, [...owners][0]);
const resolveWord = (sv) => wordByKey.get(fold(sv)) || wordByKey.get(fold(sv).replace(/\s+/g, '-')) || '';

// sentence: exact text -> slug (also folded, markup-free)
const sentByText = new Map();
for (const n of sentNotes) {
  const t = sentText(n);
  if (!sentByText.has(t)) sentByText.set(t, n.slug);
  const f = fold(t);
  if (!sentByText.has(f)) sentByText.set(f, n.slug);
}
const resolveSentence = (sv) => sentByText.get(clean(sv)) || sentByText.get(fold(clean(sv))) || '';

// reverse map: word slug -> sentence notes that list it
const sentencesOfWord = new Map();
for (const n of sentNotes) {
  for (const w of n.words || []) {
    if (!sentencesOfWord.has(w)) sentencesOfWord.set(w, new Set());
    sentencesOfWord.get(w).add(n.slug);
  }
}
const topicZh = new Map(notes.filter((n) => n.type === 'topic').map((n) => [n.slug, clean(n.zh)]));

// ---------------------------------------------------------------- words
const cov = { grammarTip: 0, grammarTotal: 0 };

function frontmatterGenus(n) {
  const rel = bodies[n.slug] && bodies[n.slug].path;
  if (rel) {
    try {
      const t = fs.readFileSync(path.join(repoRoot, rel), 'utf8').slice(0, 1500);
      const m = /^genus:\s*"?([A-Za-zåäö]*)"?/m.exec(t);
      if (m && /^(en|ett)$/.test(m[1])) return m[1];
    } catch (e) { /* fall through to header */ }
  }
  const h = /^#[^\n]*?\((en|ett)\)/m.exec(bodyOf(n.slug).split('\n')[0] || '');
  return h ? h[1] : '';
}

function extractIpa(body) {
  const m = /^发音提示[：:](.*)$/m.exec(body);
  if (!m) return '';
  const line = m[1];
  const slash = /\/([^\/\n]{2,60})\//.exec(line);
  if (slash && !CJK.test(slash[1]) && !/\s{2,}/.test(slash[1])) return `/${slash[1].trim()}/`;
  const br = /\[([^\]\n]{2,60})\]/.exec(line);
  if (br && !CJK.test(br[1]) && /[ˈˌːɛɑɔʉɧŋɕʂɪʏøæɡ:]/.test(br[1])) return `/${br[1].replace(/^["']/, 'ˈ').trim()}/`;
  return '';
}

function extractDef(body) {
  const m = /Förklaring:\s*(.+)$/m.exec(body);
  return m ? clean(m[1]) : '';
}

function pickWordExample(n, body, P) {
  const fits = (sv, zh) => sv.length >= 8 && sv.length <= P.exSvMax && zh.length <= P.exZhMax;
  // 1) shortest linked sentence note with Chinese
  const linked = new Set([...(n.sentences || []), ...(sentencesOfWord.get(n.slug) || [])]);
  let best = null;
  for (const slug of [...linked].sort()) {
    const s = sentBySlug.get(slug);
    if (!s || !s.zh) continue;
    const sv = sentText(s);
    const zh = clean(s.zh);
    if (!sv || !zh || !fits(sv, zh)) continue;
    if (!best || sv.length < best[0].length) best = [sv, zh];
  }
  if (best) return best;
  // 2) example line from the word body (prefer ones that contain the lemma or a form)
  const pairs = examplePairs(body).filter(([sv, zh]) => fits(sv, zh));
  if (!pairs.length) return null;
  const keys = [n.lemma || n.slug, ...(n.forms || [])].map(fold).filter(Boolean);
  const hit = pairs.filter(([sv]) => {
    const toks = new Set(fold(sv).split(/[^a-zåäöé0-9-]+/));
    return keys.some((k) => toks.has(k));
  });
  const pool = hit.length ? hit : pairs;
  return pool.reduce((a, b) => (b[0].length < a[0].length ? b : a));
}

function buildWords(P, covered) {
  const out = [];
  const topicsUsed = new Set();
  for (const n of wordNotes) {
    const body = bodyOf(n.slug);
    const p = fold(n.ordklass).split(/[\s/(,]/)[0] || '';
    const isNoun = p === 'substantiv';
    const g = isNoun ? frontmatterGenus(n) : '';
    const ipa = extractIpa(body);
    const def = cut(extractDef(body), P.defMax);
    const ex = P.exOnlyUncovered && covered.has(n.slug) ? null : pickWordExample(n, body, P);
    const lemma = clean(n.lemma || n.title);
    const f = [];
    for (const x of [lemma, ...(n.forms || [])]) {
      const c = clean(x).replace(/^att\s+/, '').replace(/^\(?har\)?\s+/, '').replace(/[!?]+$/, '').trim();
      if (c && !f.includes(c)) f.push(c);
      if (f.length >= P.fMax) break;
    }
    const tp = (n.topics || []).find((t) => topicZh.has(t)) || '';
    if (tp) topicsUsed.add(tp);
    out.push({
      s: n.slug,
      l: lemma,
      p,
      g,
      c: n.cefr || '',
      lv: n.lv || '',
      zh: clean(n.zh),
      en: clean(n.en),
      ipa,
      def,
      ex: ex || null,
      f,
      tp,
      d: n.created || '',
      k: n.known ? 1 : 0,
      gap: gapSlugs.has(n.slug) ? 1 : 0,
    });
  }
  if (P.slimN) {
    // Last resort when even the trimmed ladder is over budget: the lowest-priority words
    // (not a gap word, lowest CEFR, oldest) lose def + ex and stay as bare quiz/pair material.
    const rank = { A1: 0, A2: 1, B1: 2, B2: 3, C1: 4, C2: 5 };
    const order = out
      .slice()
      .sort((a, b) => a.gap - b.gap || (rank[a.c] ?? 2) - (rank[b.c] ?? 2) || cmp(a.d, b.d) || cmp(a.s, b.s));
    for (const w of order.slice(0, P.slimN)) { w.def = ''; w.ex = null; }
  }
  return { out, topicsUsed };
}

// ---------------------------------------------------------------- sentences
function buildSentences(P) {
  const rows = [];
  for (const n of sentNotes) {
    const sv = sentText(n);
    const zh = clean(n.zh);
    if (!zh || !CJK.test(zh) || zh.length > 140 || sv.length < 20 || sv.length > 110) continue;
    rows.push({
      s: n.slug,
      sv,
      zh,
      w: [...new Set((n.words || []).filter((w) => wordBySlug.has(w)))],
      c: n.cefr || '',
      lv: n.lv || '',
      d: n.created || '',
    });
  }
  rows.sort((a, b) => cmp(b.d, a.d) || cmp(a.s, b.s)); // newest first, stable
  return rows.slice(0, P.sentMax).sort((a, b) => cmp(a.s, b.s));
}

// ---------------------------------------------------------------- phrases
function buildPhrases(P) {
  const out = [];
  for (const n of notes.filter((x) => x.type === 'phrase').sort((a, b) => cmp(a.slug, b.slug))) {
    const sv = clean(n.phrase || n.title);
    const zh = clean(n.zh);
    if (!sv || !zh) continue;
    const pairs = P.phraseEx ? examplePairs(bodyOf(n.slug)).filter(([s, z]) => s.length <= P.exSvMax && z.length <= P.exZhMax) : [];
    out.push({
      s: n.slug,
      sv,
      zh: cut(zh, 80),
      en: cut(clean(n.en), 80),
      cat: clean(n.category || ''),
      ex: pairs.length ? pairs.reduce((a, b) => (b[0].length < a[0].length ? b : a)) : null,
      d: n.created || '',
      lv: n.lv || '',
    });
  }
  return out;
}

// ---------------------------------------------------------------- grammar
function buildGrammar() {
  const out = [];
  let tipN = 0;
  for (const n of notes.filter((x) => x.type === 'grammar').sort((a, b) => cmp(a.slug, b.slug))) {
    const body = bodyOf(n.slug);
    const tipM = /^一句话[:：]\s*(.+)$/m.exec(body);
    const lvlM = /^级别[:：]\s*([A-C][12](?:[–-][A-C][12])?)/m.exec(body);
    const tip = tipM ? cut(clean(tipM[1]), 160) : '';
    if (tip) tipN += 1;
    const pairs = examplePairs(body).filter(([s, z]) => s.length <= 110 && z.length <= 80).slice(0, 2);
    out.push({
      s: n.slug,
      name: clean(n.name || n.title),
      zh: clean(n.zh),
      tip,
      ex: pairs.map(([a, b]) => [a, b]),
      lvl: (lvlM && lvlM[1]) || n.cefr || '',
      lv: n.lv || '',
    });
  }
  cov.grammarTip = tipN;
  cov.grammarTotal = out.length;
  return out;
}

// ---------------------------------------------------------------- articles / bites
const ARTICLE_SITE = (a) => (a.kind === 'scenario' ? 'tala' : 'reading');

function articleTitle(a) {
  let t = String(a.title || '').replace(/^🇸🇪\s*/, '');
  t = t.replace(/\s*[（(][^()（）]*[)）]\s*$/u, (m) => (CJK.test(m) || / \/ /.test(m) ? '' : m));
  const k = t.indexOf(' — ');
  if (k > 0) {
    const tail = t.slice(k + 3);
    const cjk = (tail.match(/[㐀-鿿]/g) || []).length;
    if (cjk / Math.max(tail.length, 1) > 0.3) t = t.slice(0, k);
  }
  return clean(t);
}

// word surface forms of one article's resolved words -> slug (for per-bite keyword picking)
function articleWordMap(slugs) {
  const m = new Map();
  for (const s of slugs) {
    const n = wordBySlug.get(s);
    for (const f of [n.lemma || n.slug, ...(n.forms || [])]) {
      const k = fold(f);
      if (k && !/\s/.test(k) && !m.has(k)) m.set(k, s);
    }
  }
  return m;
}
function wordsInText(text, fmap, order, max, pad) {
  const found = [];
  for (const tok of fold(text).split(/[^a-zåäöé0-9-]+/)) {
    const s = fmap.get(tok);
    if (s && !found.includes(s)) found.push(s);
  }
  // unknown words first (they are what the card is for), keep text order inside each group
  found.sort((a, b) => (wordBySlug.get(a).known ? 1 : 0) - (wordBySlug.get(b).known ? 1 : 0));
  let res = found.slice(0, max);
  if (pad && res.length < pad) for (const s of order) { if (res.length >= pad) break; if (!res.includes(s)) res.push(s); }
  return res;
}

function sections(body) {
  const lines = String(body).split('\n');
  const grab = (re) => {
    const start = lines.findIndex((l) => /^## /.test(l) && re.test(l));
    if (start < 0) return null;
    const out = [];
    for (let i = start + 1; i < lines.length; i += 1) {
      if (/^## /.test(lines[i]) || /^---\s*$/.test(lines[i])) break;
      out.push(lines[i]);
    }
    return out.join('\n');
  };
  return { sv: grab(/瑞典语原文|Källtext/), zh: grab(/全文翻译|Översättning/) };
}
function paragraphs(text, isZh) {
  if (!text) return [];
  const out = [];
  for (const raw of text.split(/\n\s*\n/)) {
    const lines = raw.split('\n').map((l) => l.trim()).filter(Boolean);
    if (!lines.length) continue;
    if (/^(#|[-*] |\||>|\d+\. )/.test(lines[0])) continue;
    let joined = lines.join(' ');
    if (isZh) joined = joined.replace(/🇨🇳\s*/g, '');
    if (/^\*\*[^*]*\*\*$/.test(joined.trim())) continue; // bold-only line = a title
    if (lines.every((l) => /^\*\*[^*]*\*\*$/.test(l.replace(/🇨🇳\s*/g, '')))) continue;
    out.push(clean(joined));
  }
  return out;
}
const INSTRUCTION = /^(Läs|Lyssna|Svara|Skriv|Titta|Till:|Ämne:|Från:|Hej,?$)/;

function newsBites(a, fmapOrder) {
  const out = [];
  const body = String(a.body || '');
  const re = /^## (\d+)\.\s*(.*)$/gm;
  const heads = [];
  let m;
  while ((m = re.exec(body))) heads.push({ n: Number(m[1]), title: m[2], at: m.index, end: m.index + m[0].length });
  heads.forEach((h, i) => {
    const stop = i + 1 < heads.length ? heads[i + 1].at : body.length;
    let chunk = body.slice(h.end, stop);
    const hr = chunk.search(/^---\s*$/m);
    if (hr >= 0) chunk = chunk.slice(0, hr);
    const lines = chunk.split('\n').map((l) => l.trim()).filter(Boolean);
    const zi = lines.findIndex((l) => l.startsWith('🇨🇳'));
    const svLines = (zi >= 0 ? lines.slice(0, zi) : lines).filter((l) => !/^[#>]/.test(l));
    const zhLines = zi >= 0 ? lines.slice(zi) : [];
    const sv = clean(svLines.join(' '));
    if (sv.length < 30) return;
    const fit = fitSv(sv, 380);
    const zh = alignZh(clean(zhLines.join(' ').replace(/🇨🇳\s*/g, '')), fit, true);
    out.push({
      id: `${a.slug}#${h.n}`,
      kind: 'news',
      a: a.slug,
      site: ARTICLE_SITE(a),
      title: clean(h.title.replace(/^[–—-]\s*/, '')),
      d: a.date,
      c: a.cefr || '',
      lv: a.lv || '',
      sv: fit.text,
      zh,
      words: wordsInText(fit.text, fmapOrder.fmap, fmapOrder.order, 8, 0),
    });
  });
  return out;
}

function teaserBite(a, fmapOrder) {
  const sec = sections(a.body);
  if (!sec.sv) return null;
  const svp = paragraphs(sec.sv, false);
  const zhp = paragraphs(sec.zh, true);
  const idx = svp.findIndex((p) => p.length >= 40 && !INSTRUCTION.test(p));
  if (idx < 0) return null;
  const fit = fitSv(svp[idx], 380);
  if (fit.text.length < 30) return null;
  const zh = svp.length === zhp.length ? alignZh(zhp[idx], fit, false) : '';
  return {
    id: `${a.slug}#t`,
    kind: 'teaser',
    a: a.slug,
    site: ARTICLE_SITE(a),
    title: articleTitle(a),
    d: a.date,
    c: a.cefr || '',
    lv: a.lv || '',
    sv: fit.text,
    zh,
    words: wordsInText(fit.text, fmapOrder.fmap, fmapOrder.order, 8, 3),
  };
}

function dialogBites(a, fmapOrder) {
  const dlg = a.dialog;
  const label = new Map(((dlg && dlg.speakers) || []).map((s) => [s.key, clean(s.label || s.key)]));
  const turns = ((dlg && dlg.turns) || []).map((t) => ({ who: label.get(t.s) || clean(t.s), sv: clean(t.sv), zh: clean(t.zh) }));
  const ok = (win) => win.length >= 3 && win.every((t) => t.sv && t.zh && t.sv.length <= 160 && t.zh.length <= 160);
  const out = [];
  let i = 0;
  while (i < turns.length && out.length < 3) {
    let win = turns.slice(i, i + 4);
    if (!ok(win)) win = turns.slice(i, i + 3);
    if (ok(win) && win.length >= 3) {
      out.push({
        id: `${a.slug}#d${out.length + 1}`,
        kind: 'dialog',
        a: a.slug,
        site: ARTICLE_SITE(a),
        title: articleTitle(a),
        d: a.date,
        c: a.cefr || '',
        lv: a.lv || '',
        sv: '',
        zh: '',
        turns: win,
        words: wordsInText(win.map((t) => t.sv).join(' '), fmapOrder.fmap, fmapOrder.order, 8, 0),
      });
      i += win.length;
    } else i += 1;
  }
  return out;
}

function buildArticlesAndBites(P, emittedSentences) {
  const dated = articles
    .map((a) => ({ ...a, date: ISO.test(a.date || '') ? a.date : dateInSlug(a.slug) }))
    .filter((a) => ISO.test(a.date))
    .sort((a, b) => cmp(b.date, a.date) || cmp(a.slug, b.slug));
  const latest = dated.length ? dated[0].date : '';
  const L = latest ? dayNum(latest) : 0;

  const bites = [];
  const fresh = [];
  const recent = [];
  for (const a of dated) {
    const wslugs = [];
    for (const w of (a.items && a.items.words) || []) {
      const s = resolveWord(w.sv);
      if (s && !wslugs.includes(s)) wslugs.push(s);
    }
    const sslugs = [];
    for (const s of (a.items && a.items.sentences) || []) {
      const slug = resolveSentence(s.sv);
      if (slug && emittedSentences.has(slug) && !sslugs.includes(slug)) sslugs.push(slug);
    }
    const fmapOrder = { fmap: articleWordMap(wslugs), order: wslugs };
    if (a.kind === 'news') bites.push(...newsBites(a, fmapOrder));
    else if (a.kind === 'scenario' && a.dialog && a.dialog.zhAligned) bites.push(...dialogBites(a, fmapOrder));
    else if (a.kind !== 'scenario' && a.kind !== 'adjsubst' && a.kind !== 'other') {
      const t = teaserBite(a, fmapOrder);
      if (t) bites.push(t);
    }
    const age = L - dayNum(a.date);
    if (age >= 0 && age <= 2) {
      fresh.push({ a: a.slug, site: ARTICLE_SITE(a), title: articleTitle(a), d: a.date, kind: 'article', words: wslugs, sentences: sslugs });
    } else if (age >= 3 && recent.length < 12) {
      // The 12 articles before the fresh window, whatever their age: a date window would be
      // empty after a pause in generation (CLAUDE.md §4.9).
      recent.push({ a: a.slug, site: ARTICLE_SITE(a), title: articleTitle(a), d: a.date, words: wslugs });
    }
  }

  const rank = { news: 0, dialog: 1, teaser: 2 };
  bites.sort((x, y) => cmp(y.d, x.d) || cmp(rank[x.kind], rank[y.kind]) || cmp(x.id, y.id));
  let kept = bites.slice(0, P.bitesMax);
  // keep all three kinds represented even if the cap cut one of them off
  for (const kind of ['news', 'dialog', 'teaser']) {
    if (!kept.some((b) => b.kind === kind)) {
      const first = bites.find((b) => b.kind === kind);
      if (first) kept = kept.slice(0, P.bitesMax - 1).concat(first);
    }
  }
  return { latest, bites: kept, fresh, recent };
}

