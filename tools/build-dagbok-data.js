#!/usr/bin/env node
// Build the Dagbok day index: one compact record per active day listing what was
// added that day — 📖 reading articles, 🎧 listening episodes, 🔍 individual
// lookups, 📝 older sources without an article — so the home page can show
// "what did I practise on day X" and link straight into Läsning / Lyssna / Sök
// without loading the multi-MB KB + reading data itself.
//
// Input is the OTHER builders' output (run them first, as the GitHub Action does):
//   site/kb-index.js                    ← tools/build-kb-site.js
//   site/reading/reading-data.js        ← tools/build-reading-site.js
//   site/listening/listening-data.js    ← tools/build-listening-site.js
// Reusing their output keeps Dagbok's titles/slugs/ids identical to what those
// pages show (the deep links must resolve) instead of re-parsing every source.
//
// Output: site/dagbok-data.js (gitignored, generated by the Action like the rest).
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const repoRoot = path.resolve(__dirname, '..');
const siteRoot = path.join(repoRoot, 'site');
const outPath = path.join(siteRoot, 'dagbok-data.js');

const INPUTS = [
  { file: 'kb-index.js', global: 'KB_INDEX', builder: 'tools/build-kb-site.js' },
  { file: 'reading/reading-data.js', global: 'READING_DATA', builder: 'tools/build-reading-site.js' },
  { file: 'listening/listening-data.js', global: 'LISTENING_DATA', builder: 'tools/build-listening-site.js' },
];

function loadInputs() {
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  for (const input of INPUTS) {
    const p = path.join(siteRoot, input.file);
    if (!fs.existsSync(p)) {
      console.error(`Missing site/${input.file} — run \`node ${input.builder}\` first.`);
      process.exit(1);
    }
    vm.runInContext(fs.readFileSync(p, 'utf8'), sandbox, { filename: input.file });
  }
  return sandbox.window;
}

const W = loadInputs();
const notes = (W.KB_INDEX && W.KB_INDEX.notes) || [];
// Only already-imported articles: Dagbok dates things by when they entered the KB.
const articles = ((W.READING_DATA && W.READING_DATA.articles) || []).filter((a) => a.status === 'imported');
const episodes = (W.LISTENING_DATA && W.LISTENING_DATA.episodes) || [];

const ITEM_TYPES = ['word', 'phrase', 'sentence', 'grammar'];
const ITEM_ORDER = { word: 0, phrase: 1, grammar: 2, sentence: 3 };
const ISO = /^\d{4}-\d{2}-\d{2}$/;

function dateInSlug(slug) {
  const m = /(\d{4}-\d{2}-\d{2})/.exec(String(slug || ''));
  return m ? m[1] : '';
}
function fold(s) {
  return String(s || '').toLowerCase().normalize('NFC');
}
function asciiFold(s) {
  return fold(s).replace(/[åä]/g, 'a').replace(/ö/g, 'o');
}
function trunc(s, n) {
  const t = String(s || '').replace(/\s+/g, ' ').trim();
  return t.length > n ? t.slice(0, n - 1) + '…' : t;
}

const days = new Map(); // date -> { reading, listening, lookups, sources }
function day(date) {
  if (!days.has(date)) days.set(date, { date, reading: [], listening: [], lookups: [], sources: [] });
  return days.get(date);
}

// ---------- 📝 sources → which article (if any) they were imported from ----------
// A source note and its readable article share a date but no exact slug, so score
// same-day candidates: identical slug tail (source-<d>-x ↔ scenario-<d>-x) wins
// outright; otherwise shared export items (words/phrases) + shared title tokens.
// Below MIN_SCORE a source counts as having no article (6 early-June notes and a
// few drills) and gets its own 📝 row instead. Calibrated 2026-10-02: every true
// match scored ≥ 8; the one false pairing (a Zlatan note vs a drill) scored 5.
const MIN_SCORE = 6;
const STOP = new Set([
  'pa', 'och', 'en', 'ett', 'i', 'att', 'med', 'av', 'om', 'till', 'eller', 'import',
  'bojning', 'scenario', 'adjsubst', 'paste', 'source', 'other', 'text', 'story', 'dialog',
]);
function tokens(s) {
  return new Set(asciiFold(s).split(/[^a-z0-9]+/).filter((t) => t.length > 1 && !/^\d+$/.test(t) && !STOP.has(t)));
}
function slugTail(slug) {
  return String(slug).replace(/^[a-z]+-\d{4}-\d{2}-\d{2}-?/, '');
}
function itemKey(sv) {
  return fold(sv).replace(/\s+/g, '-');
}

const articlesByDate = new Map();
for (const a of articles) {
  const d = a.date || dateInSlug(a.slug);
  if (!ISO.test(d)) continue;
  if (!articlesByDate.has(d)) articlesByDate.set(d, []);
  articlesByDate.get(d).push(a);
}

function sourceDate(src) {
  return String(src.date || src.date_added || src.created || '') || dateInSlug(src.slug);
}
function sourceLabel(src) {
  return String(src.source_label || src.title || src.slug).replace(/^Source:\s*/i, '');
}
function matchArticle(src, date) {
  const cands = articlesByDate.get(date) || [];
  const want = new Set([...(src.words || []), ...(src.phrases || [])].map(fold));
  const wantTok = tokens(`${src.slug} ${src.source_label || ''} ${src.title || ''}`);
  const tail = slugTail(src.slug);
  let best = null;
  let bestScore = 0;
  for (const a of cands) {
    let score = tail && tail === slugTail(a.slug) ? 1000 : 0;
    for (const it of [...a.items.words, ...a.items.phrases]) if (want.has(itemKey(it.sv))) score += 1;
    const have = tokens(`${a.slug} ${a.title}`);
    for (const t of wantTok) if (have.has(t)) score += 3;
    if (score > bestScore) { bestScore = score; best = a; }
  }
  return bestScore >= MIN_SCORE ? best : null;
}

const claimed = new Set(); // item slugs that belong to some source (not a loose lookup)
for (const src of notes) {
  if (src.type !== 'source') continue;
  let count = 0;
  for (const key of ['words', 'phrases', 'sentences', 'grammar']) {
    for (const slug of src[key] || []) { claimed.add(String(slug)); count += 1; }
  }
  const date = sourceDate(src);
  if (!ISO.test(date) || matchArticle(src, date)) continue;
  day(date).sources.push({ slug: src.slug, label: trunc(sourceLabel(src), 80), count });
}

// ---------- 📖 reading ----------
for (const [date, list] of articlesByDate) {
  for (const a of list) {
    day(date).reading.push({
      slug: a.slug,
      title: trunc(a.title.replace(/^🇸🇪\s*/, ''), 120),
      kind: a.kind,
      kindLabel: a.kindLabel ? a.kindLabel.zh : a.kind,
      cefr: a.cefr || '',
      ep: a.listening ? a.listening.id : '',
    });
  }
}

// ---------- 🎧 listening ----------
// An episode already reachable as the 🎧 link of a same-day article row isn't
// listed again; other episodes (incl. a second recording of one text) are.
const articleEp = new Set();
for (const d of days.values()) for (const r of d.reading) if (r.ep) articleEp.add(`${d.date}|${r.ep}`);
for (const ep of episodes) {
  const date = ep.date || dateInSlug(ep.id);
  if (!ISO.test(date) || articleEp.has(`${date}|${ep.id}`)) continue;
  day(date).listening.push({ id: ep.id, title: trunc(ep.title, 90), readingSlug: ep.readingSlug || '' });
}

// ---------- 🔍 lookups ----------
// Items created that day that no source claims and no same-day article exported
// — i.e. words looked up on their own (/learn, mobile, study-guide gap fills).
const articleItems = new Set();
for (const [date, list] of articlesByDate) {
  for (const a of list) for (const it of [...a.items.words, ...a.items.phrases]) articleItems.add(`${date}|${itemKey(it.sv)}`);
}
for (const n of notes) {
  if (!ITEM_TYPES.includes(n.type) || claimed.has(n.slug)) continue;
  const date = String(n.created || '');
  if (!ISO.test(date)) continue;
  const label = n.type === 'word' ? (n.lemma || n.title)
    : n.type === 'sentence' ? (n.sentence || String(n.title || '').replace(/^🇸🇪\s*/, ''))
      : (n.phrase || n.title || n.name || n.slug);
  if (articleItems.has(`${date}|${itemKey(label)}`)) continue;
  day(date).lookups.push({ slug: n.slug, type: n.type, label: trunc(label, 60), zh: trunc(n.zh, 40) });
}

// ---------- emit ----------
const out = Array.from(days.values())
  .filter((d) => d.reading.length || d.listening.length || d.lookups.length || d.sources.length)
  .sort((a, b) => b.date.localeCompare(a.date));
for (const d of out) {
  d.reading.sort((a, b) => a.kind.localeCompare(b.kind) || a.title.localeCompare(b.title));
  d.listening.sort((a, b) => a.title.localeCompare(b.title));
  d.lookups.sort((a, b) => ITEM_ORDER[a.type] - ITEM_ORDER[b.type] || a.label.localeCompare(b.label));
  d.sources.sort((a, b) => a.label.localeCompare(b.label));
}

const generatedAt =
  process.env.KB_SITE_GENERATED_AT || new Date().toISOString().replace('T', ' ').slice(0, 19);
fs.writeFileSync(outPath, `window.DAGBOK_DATA = ${JSON.stringify({ generatedAt, days: out })};\n`, 'utf8');

const sum = (k) => out.reduce((n, d) => n + d[k].length, 0);
console.log(
  `Generated ${path.relative(repoRoot, outPath)} — ${out.length} days: ` +
    `${sum('reading')} reading, ${sum('listening')} listening, ${sum('lookups')} lookups, ${sum('sources')} sources ` +
    `(${(fs.statSync(outPath).size / 1024).toFixed(0)} KB).`
);
