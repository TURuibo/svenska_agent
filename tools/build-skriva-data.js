const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const norm = (s) => String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
const unquote = (s) => String(s == null ? '' : s).trim().replace(/^['"]|['"]$/g, '');

// Flat YAML frontmatter with inline [a, b] lists.
function parseNote(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  const fm = {};
  if (!m) return { fm, body: text };
  for (const line of m[1].split(/\r?\n/)) {
    const km = line.match(/^([^\s:#][^:]*):\s*(.*)$/);
    if (!km) continue;
    const raw = km[2].trim();
    const rest = /^(["']).*\1$/.test(raw) ? raw : raw.replace(/\s+#.*$/, '').trim();   // " # comment", except inside quotes
    const list = rest.match(/^\[(.*)\]$/);
    fm[km[1].trim()] = list ? list[1].split(',').map(unquote).filter(Boolean) : unquote(rest);
  }
  return { fm, body: m[2] };
}

// "## heading" sections of a body → [{ h, lines }]. Lines before the first "## " are in `pre`.
function splitH2(body) {
  const secs = [];
  const pre = [];
  let cur = null;
  for (const line of String(body).split(/\r?\n/)) {
    const m = line.match(/^##\s+(.*)$/);
    if (m) { cur = { h: m[1].trim(), lines: [] }; secs.push(cur); continue; }
    (cur ? cur.lines : pre).push(line);
  }
  return { secs, pre };
}

// Split "a | b | c" on pipes that are not inside [[wikilinks]]; "\|" is a literal pipe.
function splitCells(s) {
  const out = [];
  let cur = '';
  let depth = 0;
  const str = String(s);
  for (let i = 0; i < str.length; i += 1) {
    const two = str.slice(i, i + 2);
    if (two === '[[') { depth += 1; cur += two; i += 1; continue; }
    if (two === ']]' && depth) { depth -= 1; cur += two; i += 1; continue; }
    if (two === '\\|') { cur += '|'; i += 1; continue; }
    if (str[i] === '|' && !depth) { out.push(cur.trim()); cur = ''; continue; }
    cur += str[i];
  }
  out.push(cur.trim());
  return out;
}
const tableCells = (line) => splitCells(line.trim().replace(/^\|/, '').replace(/\|$/, ''));
const isSepRow = (cells) => cells.every((c) => /^:?-{2,}:?$/.test(c) || c === '');

// "Svenska · 中文" → [sv, zh] (split on the first " · ").
function splitDot(s) {
  const i = String(s).indexOf(' · ');
  return i < 0 ? [String(s).trim(), ''] : [s.slice(0, i).trim(), s.slice(i + 3).trim()];
}

// The part of a phrase that is looked for in the model texts: the longest fixed stretch between "…".
function matchChunk(sv) {
  const parts = String(sv).split(/…|\.\.\./)
    .map((x) => x.replace(/^[\s,;:–—-]+|[\s,;:–—-]+$/g, '').trim())
    .filter(Boolean);
  let best = '';
  for (const p of parts) if (p.length > best.length) best = p;
  return (best.match(/[A-Za-zÅÄÖåäö]/g) || []).length >= 3 ? best.toLowerCase() : '';
}

const LETTER = /[A-Za-zÅÄÖåäöÉéÜüÀ-ÿ]/;
// Every whole-word, case-insensitive occurrence of `chunk` (already lowercase) in `text`.
function findAll(text, chunk) {
  const out = [];
  if (!chunk) return out;
  const low = text.toLowerCase();
  if (low.length !== text.length) return out;   // exotic case mapping: offsets would drift
  const headIsLetter = LETTER.test(chunk[0]);
  const tailIsLetter = LETTER.test(chunk[chunk.length - 1]);
  let from = 0;
  for (;;) {
    const i = low.indexOf(chunk, from);
    if (i < 0) break;
    const before = i > 0 ? text[i - 1] : '';
    const after = text[i + chunk.length] || '';
    if (!(headIsLetter && LETTER.test(before)) && !(tailIsLetter && LETTER.test(after))) out.push(i);
    from = i + chunk.length;
  }
  return out;
}

// ---------------------------------------------------------------- the model texts (imported/<slug>.md)
function sectionOf(text, re) {
  const lines = text.split(/\r?\n/);
  const start = lines.findIndex((l) => /^##\s/.test(l) && re.test(l));
  if (start < 0) return null;
  let end = lines.slice(start + 1).findIndex((l) => /^##\s/.test(l));
  end = end < 0 ? lines.length : start + 1 + end;
  return lines.slice(start + 1, end).join('\n');
}
function blocksOf(section) {
  return String(section || '').split(/\n[ \t]*\n/)
    .map((b) => b.split('\n').map((l) => l.replace(/[ \t]+$/, '')).join('\n').trim())
    .filter((b) => b && !/^(---+|\*\*\*+|___+)$/.test(b));
}
const articleCache = new Map();
function loadArticle(slug) {
  if (articleCache.has(slug)) return articleCache.get(slug);
  const file = path.join(importedDir, `${slug}.md`);
  let a = null;
  if (fs.existsSync(file)) {
    const text = fs.readFileSync(file, 'utf8');
    let title = ((text.match(/^#\s+(.*)$/m) || [])[1] || slug).replace(/^🇸🇪\s*/, '').trim();
    let sub = '';
    const pm = title.match(/\s*[（(]([^（）()]*)[）)]\s*$/);
    if (pm) { sub = pm[1].trim(); title = title.slice(0, pm.index).trim(); }
    a = {
      title,
      sub,
      cefr: ((text.match(/^\*\*CEFR[^:：*]*[:：]\*\*\s*(.*)$/m) || [])[1] || '').trim(),
      sv: blocksOf(sectionOf(text, /瑞典语原文|🇸🇪\s*原文/)),
      zh: blocksOf(sectionOf(text, /全文翻译/)),
      kurs: /^##\s+🔍\s*逐段精读/m.test(text) ? 1 : 0,
    };
  }
  articleCache.set(slug, a);
  return a;
}
