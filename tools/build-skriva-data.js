const genreFiles = fs.existsSync(srcDir) ? fs.readdirSync(srcDir).filter((f) => f.endsWith('.md') && !f.startsWith('_')).sort() : [];
const built = genreFiles.map((f) => buildGenre(f));
const genres = built.map((b) => b.data).sort((a, b) => a.order - b.order || cmp(a.key, b.key));
const genreKeys = new Set(genres.map((g) => g.key));
if (!genres.length) warn('skriva/', '还没有体裁文件（skriva/<key>.md）');

const mina = (fs.existsSync(mineDir) ? fs.readdirSync(mineDir).filter((f) => f.endsWith('.md') && !f.startsWith('_')).sort() : [])
  .map((f) => buildMine(f, genreKeys)).filter(Boolean)
  .sort((a, b) => cmp(b.date, a.date) || cmp(b.id, a.id));
const typer = {};
for (const m of mina) for (const r of m.rows) if (r.typ) typer[r.typ] = (typer[r.typ] || 0) + 1;

for (const g of genres) {
  const inText = g.phrases.filter((p) => p.src.length).length;
  console.log(`${g.icon} ${g.key}: 骨架 ${g.slots.length} 格 · 句型 ${g.phrases.length}（范文里有 ${inText}，补充 ${g.phrases.length - inText}）· ` +
    `范文 ${g.texts.length} · 更多 ${g.more.length} · 写作题 ${g.tasks.length} · 自查 ${g.checks.reduce((n, c) => n + c.items.length, 0)} 条`);
  for (const t of g.texts) {
    const hl = t.blocks.reduce((n, b) => n + b.hl.length, 0);
    console.log(`   📄 ${t.slug} — 正文 ${t.blocks.length} 块 · ${t.words} 词 · 高亮 ${hl} 处（${new Set([].concat(...t.blocks.map((b) => b.hl.map((h) => h[2])))).size} 个句型）`);
  }
  if (CHECK) {
    const sup = built.find((b) => b.data === g).supplementary;
    if (sup.length) console.log(`   ➕ 补充句型（范文里没有，请确认瑞典语无误）：${sup.map((p) => p.sv).join(' · ')}`);
  }
}
if (mina.length) console.log(`📂 我的作文 ${mina.length} 篇 · 常错类型 ${Object.entries(typer).sort((a, b) => b[1] - a[1]).map(([k, n]) => `${k} ${n}`).join(' · ') || '—'}`);

for (const w of warnings) console.warn(`⚠️  ${w}`);
for (const e of errors) console.error(`❌ ${e}`);

