const pageOf = (slug) => (/^scenario-/.test(slug) && !/^scenario-\d{4}-\d{2}-\d{2}-fokus-/.test(slug) ? 'tala' : 'reading');

function grammarName(slug) {
  const file = path.join(grammarDir, `${slug}.md`);
  if (!fs.existsSync(file)) return null;
  const { fm } = parseNote(fs.readFileSync(file, 'utf8'));
  return { slug, name: unquote(fm.name) || slug.replace(/^grammar-/, ''), zh: unquote(fm.zh) };
}

// ---------------------------------------------------------------- one genre file
function parseSkeleton(lines, file) {
  const slots = [];
  const phrases = [];
  let slot = null;
  let group = null;
  for (const raw of lines) {
    const line = raw.trim();
    let m;
    if ((m = line.match(/^###\s+(\d+)\.\s+(.+)$/))) {
      const [sv, zh] = splitDot(m[2]);
      slot = { n: Number(m[1]), sv, zh, what: '', groups: [] };
      group = null;
      slots.push(slot);
      if (!zh) err(file, `骨架「${m[2]}」缺中文（写成「瑞典语 · 中文」）`);
    } else if ((m = line.match(/^####\s+(.+)$/))) {
      if (!slot) { err(file, `小组「${m[1]}」前面没有骨架格子（### 1. …）`); continue; }
      const [sv, zh] = splitDot(m[1]);
      group = { sv, zh, phrases: [] };
      slot.groups.push(group);
    } else if ((m = line.match(/^写什么[:：]\s*(.*)$/))) {
      if (slot) slot.what = m[1].trim();
    } else if ((m = line.match(/^[-*]\s+(.+)$/))) {
      if (!slot) { err(file, `句型「${m[1]}」前面没有骨架格子`); continue; }
      const cells = splitCells(m[1]);
      if (!cells[0] || !cells[1]) { err(file, `句型缺中文：「${m[1]}」（写成「- 瑞典语 | 中文 | 用法」）`); continue; }
      if (!group) { group = { sv: '', zh: '', phrases: [] }; slot.groups.push(group); }
      group.phrases.push(phrases.length);
      phrases.push({ sv: cells[0], zh: cells[1], note: cells.slice(2).join(' | '), slot: slot.n, m: matchChunk(cells[0]), src: [] });
    }
  }
  slots.forEach((s, i) => {
    if (s.n !== i + 1) err(file, `骨架序号不连续：第 ${i + 1} 格写的是 ${s.n}`);
    if (!s.what) err(file, `骨架 ${s.n}.「${s.sv}」缺「写什么:」`);
    if (!s.groups.some((g) => g.phrases.length)) warn(file, `骨架 ${s.n}.「${s.sv}」没有句型`);
  });
  const seen = new Map();
  phrases.forEach((p) => {
    const k = p.sv.toLowerCase();
    if (seen.has(k)) warn(file, `句型重复：「${p.sv}」（骨架 ${seen.get(k)} 和 ${p.slot}）`);
    else seen.set(k, p.slot);
    if (/(^|[^*])\*[^*\s][^*]*\*(?!\*)/.test(`${p.sv} ${p.zh} ${p.note}`)) warn(file, `句型里有单星号斜体（页面不渲染）：「${p.sv}」`);
  });
  return { slots, phrases };
}

function parseModels(lines, file) {
  const models = [];
  let cur = null;
  let inNotes = false;
  for (const raw of lines) {
    const line = raw.trim();
    let m;
    if ((m = line.match(/^###\s+(\S+)\s*$/))) {
      cur = { slug: m[1], name: '', sheet: '', taskN: 0, rows: [], notes: [] };
      inNotes = false;
      models.push(cur);
      continue;
    }
    if (/^###\s/.test(line)) { err(file, `范文标题看不懂：「${line}」（写成「### <imported/ 里的文件名，不含 .md>」，后面不要加别的）`); cur = null; continue; }
    if (!cur || !line) continue;
    if ((m = line.match(/^名称[:：]\s*(.*)$/))) { cur.name = m[1].trim(); inNotes = false; continue; }
    if ((m = line.match(/^讲义[:：]\s*(.*)$/))) { cur.sheet = m[1].trim(); inNotes = false; continue; }
    if ((m = line.match(/^任务块[:：]\s*(\d+)/))) { cur.taskN = Number(m[1]); inNotes = false; continue; }
    if (/^亮点[:：]/.test(line)) { inNotes = true; continue; }
    if (/^\|/.test(line)) {
      inNotes = false;
      const cells = tableCells(line);
      if (isSepRow(cells) || /^开头$/.test(cells[0])) continue;
      const sm = String(cells[1] || '').match(/^(\d+)(?:\s*\+\s*(\d+))?(?:\s*·\s*(.+))?$/);
      if (!sm) { err(file, `范文 ${cur.slug}：「骨架」列看不懂：「${cells[1]}」（写序号，如 4 或 4 · råd 1 或 6+7）`); continue; }
      cur.rows.push({ prefix: cells[0], slot: Number(sm[1]), slot2: sm[2] ? Number(sm[2]) : 0, sub: (sm[3] || '').trim(), what: cells.slice(2).join(' | ') });
      continue;
    }
    if (inNotes && (m = line.match(/^[-*]\s+(.+)$/))) cur.notes.push(m[1].trim());
  }
  return models;
}

function parseTasks(lines, file) {
  const tasks = [];
  let cur = null;
  let mode = '';
  for (const raw of lines) {
    const line = raw.trim();
    let m;
    if ((m = line.match(/^###\s+(U\d+)\s*·\s*(.+)$/))) {
      cur = { id: m[1], sv: m[2].trim(), zh: '', cefr: '', len: [0, 0], model: '', sit: { sv: '', zh: '' }, req: [], hints: [] };
      mode = '';
      tasks.push(cur);
      continue;
    }
    if (/^###\s/.test(line)) { err(file, `写作题标题看不懂：「${line}」（写成「### U1 · 瑞典语题目」）`); cur = null; continue; }
    if (!cur || !line) continue;
    if ((m = line.match(/^中文[:：]\s*(.*)$/))) { cur.zh = m[1].trim(); mode = ''; continue; }
    if ((m = line.match(/^级别[:：]\s*(.*)$/))) { cur.cefr = m[1].trim(); mode = ''; continue; }
    if ((m = line.match(/^长度[:：]\s*(\d+)\s*[–—-]\s*(\d+)/))) { cur.len = [Number(m[1]), Number(m[2])]; mode = ''; continue; }
    if ((m = line.match(/^仿[:：]\s*(\S+)/))) { cur.model = m[1]; mode = ''; continue; }
    if ((m = line.match(/^🇸🇪\s*(.+)$/))) { cur.sit.sv = cur.sit.sv ? `${cur.sit.sv} ${m[1].trim()}` : m[1].trim(); mode = ''; continue; }
    if ((m = line.match(/^🇨🇳\s*(.+)$/))) { cur.sit.zh = cur.sit.zh ? `${cur.sit.zh} ${m[1].trim()}` : m[1].trim(); mode = ''; continue; }
    if (/^要求[:：]/.test(line)) { mode = 'req'; continue; }
    if (/^提示[:：]/.test(line)) { mode = 'hints'; continue; }
    if (mode && (m = line.match(/^[-*]\s+(.+)$/))) {
      const cells = splitCells(m[1]);
      cur[mode].push({ sv: cells[0], zh: cells.slice(1).join(' | ') });
    }
  }
  // A task with an error is reported and left out of the data (the page never shows half a task).
  const ids = new Set();
  const good = [];
  for (const t of tasks) {
    const at = `写作题 ${t.id}`;
    const before = errors.length;
    if (ids.has(t.id)) err(file, `${at}：编号重复`);
    ids.add(t.id);
    if (!t.zh) err(file, `${at}：缺「中文:」`);
    if (!t.sit.sv || !t.sit.zh) err(file, `${at}：缺 🇸🇪 / 🇨🇳 情境`);
    if (t.req.length < 2) err(file, `${at}：「要求:」至少 2 条`);
    if (t.req.some((r) => !r.sv || !r.zh)) err(file, `${at}：每条要求都要「瑞典语 | 中文」`);
    if (!(t.len[0] > 0 && t.len[1] >= t.len[0])) err(file, `${at}：缺「长度: 80–120」`);
    if (!t.cefr) warn(file, `${at}：没写「级别:」`);
    if (errors.length === before) good.push(t);
  }
  return good;
}

function parseChecks(lines) {
  const checks = [];
  let cur = null;
  for (const raw of lines) {
    const line = raw.trim();
    let m;
    if ((m = line.match(/^###\s+(.+)$/))) { cur = { name: m[1].trim(), items: [] }; checks.push(cur); continue; }
    if ((m = line.match(/^[-*]\s+(?:\[[ xX]?\]\s*)?(.+)$/))) {
      if (!cur) { cur = { name: '', items: [] }; checks.push(cur); }
      cur.items.push(m[1].trim());
    }
  }
  return checks.filter((c) => c.items.length);
}

function parseMore(lines, file) {
  const more = [];
  for (const raw of lines) {
    const m = raw.trim().match(/^[-*]\s+(.+)$/);
    if (!m) continue;
    const cells = splitCells(m[1]);
    const a = loadArticle(cells[0]);
    if (!a) { err(file, `更多范文：imported/${cells[0]}.md 不存在`); continue; }
    more.push({ slug: cells[0], title: a.title, note: cells.slice(1).join(' | '), page: pageOf(cells[0]) });
  }
  return more;
}

function buildGenre(fileName) {
  const file = `skriva/${fileName}`;
  const { fm, body } = parseNote(fs.readFileSync(path.join(srcDir, fileName), 'utf8'));
  const key = fileName.replace(/\.md$/, '');
  if (fm.key && fm.key !== key) err(file, `frontmatter key「${fm.key}」和文件名不一致`);
  for (const k of ['sv', 'zh', 'icon']) if (!fm[k]) err(file, `frontmatter 缺 ${k}`);
  const { secs, pre } = splitH2(body);
  const find = (re, not) => secs.find((s) => re.test(s.h) && !(not && not.test(s.h)));
  const line = (re) => { const l = pre.map((x) => x.trim()).find((x) => re.test(x)); return l ? l.replace(re, '').trim() : ''; };

  const sk = find(/骨架|Disposition/i);
  const md = find(/范文|Modelltext/i, /更多|Fler/i);
  const mo = find(/更多|Fler exempel/i);
  const ta = find(/练笔|Skrivuppgift/i);
  const ch = find(/自查|Checklist/i);
  const co = find(/对比|Jämför/i);
  if (!sk) err(file, '缺「## 🧱 骨架与句型」');
  if (!md) err(file, '缺「## 📄 范文」');
  if (!ta) err(file, '缺「## ✍️ 练笔」');
  if (!ch) warn(file, '没有「## ✅ 自查清单」');

  const { slots, phrases } = parseSkeleton(sk ? sk.lines : [], file);
  if (sk && slots.length < 3) err(file, `骨架只有 ${slots.length} 格（至少 3 格）`);
  const slotNs = new Set(slots.map((s) => s.n));

  const texts = [];
  for (const mdl of parseModels(md ? md.lines : [], file)) {
    const at = `范文 ${mdl.slug}`;
    const a = loadArticle(mdl.slug);
    if (!a) { err(file, `${at}：imported/${mdl.slug}.md 不存在`); continue; }
    if (!a.sv.length) { err(file, `${at}：文章里没有「## 瑞典语原文」`); continue; }
    if (!mdl.name) err(file, `${at}：缺「名称:」`);
    const body = a.sv.slice(mdl.taskN);
    if (mdl.rows.length !== body.length) {
      err(file, `${at}：正文有 ${body.length} 块（原文 ${a.sv.length} 块 − 任务块 ${mdl.taskN}），表里有 ${mdl.rows.length} 行`);
      continue;
    }
    const zhOk = a.zh.length === a.sv.length;
    if (!zhOk) err(file, `${at}：翻译 ${a.zh.length} 块，原文 ${a.sv.length} 块，对不上（中文不显示）`);
    let prevSlot = 0;
    const blocks = body.map((sv, i) => {
      const row = mdl.rows[i];
      if (!norm(sv).startsWith(norm(row.prefix))) err(file, `${at}：第 ${i + 1} 行「${row.prefix}」对不上正文第 ${i + 1} 块「${norm(sv).slice(0, 30)}…」`);
      for (const n of [row.slot, row.slot2].filter(Boolean)) if (!slotNs.has(n)) err(file, `${at}：第 ${i + 1} 行用了不存在的骨架序号 ${n}`);
      if (row.slot < prevSlot) warn(file, `${at}：第 ${i + 1} 行骨架序号 ${row.slot} 比上一行 ${prevSlot} 小（顺序倒了？）`);
      prevSlot = row.slot;
      if (!row.what) err(file, `${at}：第 ${i + 1} 行缺「这一块在做什么」`);
      // Highlights: longest phrase first, no overlaps.
      const cands = [];
      phrases.forEach((p, pi) => { for (const start of findAll(sv, p.m)) cands.push({ start, len: p.m.length, pi }); });
      cands.sort((x, y) => y.len - x.len || x.start - y.start || x.pi - y.pi);
      const taken = [];
      for (const c of cands) if (!taken.some((t) => c.start < t.start + t.len && t.start < c.start + c.len)) taken.push(c);
      taken.sort((x, y) => x.start - y.start);
      for (const t of taken) if (!phrases[t.pi].src.includes(mdl.slug)) phrases[t.pi].src.push(mdl.slug);
      return { sv, zh: zhOk ? a.zh[mdl.taskN + i] : '', slot: row.slot, slot2: row.slot2, sub: row.sub, what: row.what, hl: taken.map((t) => [t.start, t.len, t.pi]) };
    });
    const distinct = new Set([].concat(...blocks.map((b) => b.hl.map((h) => h[2])))).size;
    if (distinct < 4) warn(file, `${at}：正文里只找到 ${distinct} 个句型（「填句型」练习至少要 4 个）`);
    if (!mdl.notes.length) warn(file, `${at}：没有「亮点:」`);
    texts.push({
      slug: mdl.slug,
      name: mdl.name || a.title,
      sheet: mdl.sheet || a.sub,
      title: a.title,
      cefr: a.cefr,
      words: (body.join(' ').match(/[A-Za-zÅÄÖåäöÉé]+(?:-[A-Za-zÅÄÖåäöÉé]+)*/g) || []).length,
      kurs: a.kurs,
      page: pageOf(mdl.slug),
      task: a.sv.slice(0, mdl.taskN).map((sv, i) => ({ sv, zh: zhOk ? a.zh[i] : '' })),
      blocks,
      notes: mdl.notes,
    });
  }
  if (md && !texts.length) err(file, '没有一篇可用的范文');

  const tasks = parseTasks(ta ? ta.lines : [], file);
  if (ta && !tasks.length) err(file, '没有一道可用的写作题（### U1 · …）');
  const textSlugs = new Set(texts.map((t) => t.slug));
  for (const t of tasks) {
    if (t.model && !textSlugs.has(t.model)) { err(file, `写作题 ${t.id}：「仿:」的 ${t.model} 不是本体裁的范文`); t.model = ''; }
  }

  const grammar = [];
  for (const g of [].concat(fm.grammar || [])) {
    const info = grammarName(g);
    if (info) grammar.push(info); else warn(file, `语法笔记 ${g} 不存在`);
  }
  const supplementary = phrases.filter((p) => !p.src.length);
  return {
    data: {
      key,
      sv: fm.sv || key,
      zh: fm.zh || '',
      icon: fm.icon || '✍️',
      cefr: fm.cefr || '',
      order: Number(fm.order) || 99,
      one: line(/^一句话[:：]\s*/),
      when: line(/^什么时候写[:：]\s*/),
      grammar,
      slots,
      phrases,
      compare: co ? co.lines.join('\n').trim() : '',
      compareT: co ? co.h.replace(/\s*[（(][^（）()]*[）)]\s*$/, '').trim() : '',
      texts,
      more: parseMore(mo ? mo.lines : [], file),
      tasks,
      checks: parseChecks(ch ? ch.lines : []),
    },
    supplementary,
  };
}

// ---------------------------------------------------------------- corrected texts (skriva/texter/*.md)
function buildMine(fileName, genreKeys) {
  const file = `skriva/texter/${fileName}`;
  const { fm, body } = parseNote(fs.readFileSync(path.join(mineDir, fileName), 'utf8'));
  const { secs } = splitH2(body);
  const sec = (re) => { const s = secs.find((x) => re.test(x.h)); return s ? s.lines : null; };
  const textOf = (lines) => (lines || []).join('\n').replace(/^\s*\n+|\n+\s*$/g, '');
  const original = textOf(sec(/Min text/i));
  if (!original) { err(file, '缺「## ✍️ Min text」'); return null; }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(fm.date || '')) err(file, 'frontmatter 缺 date（YYYY-MM-DD）');
  if (fm.genre && !genreKeys.has(fm.genre)) warn(file, `genre「${fm.genre}」不是已有的体裁`);
  if (fm.omdome && !OMDOME.includes(fm.omdome)) warn(file, `omdome「${fm.omdome}」不是 ${OMDOME.join(' / ')}`);
  const rows = [];
  for (const raw of sec(/Rättningar/i) || []) {
    if (!/^\s*\|/.test(raw)) continue;
    const c = tableCells(raw);
    if (isSepRow(c) || /^#$/.test(c[0]) || c.length < 4) continue;
    const typ = String(c[3] || '').replace(/[`*_]/g, '').trim().toLowerCase();
    if (typ && !TYPER.includes(typ)) warn(file, `批改类型「${c[3]}」不在 10 个类型里`);
    rows.push({ min: c[1] || '', ratt: c[2] || '', typ, why: c.slice(4).join(' | ') });
  }
  const list = (re) => (sec(re) || []).map((l) => l.trim().match(/^[-*]\s+(.+)$/)).filter(Boolean).map((m) => m[1].trim());
  return {
    id: fileName.replace(/\.md$/, ''),
    date: fm.date || '',
    genre: fm.genre || '',
    uppgift: fm.uppgift || '',
    titel: fm.titel || '',
    ord: Number(fm.ord) || (original.match(/\S+/g) || []).length,
    omdome: fm.omdome || '',
    original,
    rattad: textOf(sec(/Rättad text/i)),
    rows,
    uppgiften: list(/Uppgiften/i).map((t) => { const m = t.match(/^(✅|⚠️|❌)\s*(.*)$/u); return m ? { mark: m[1], text: m[2] } : { mark: '', text: t }; }),
    total: list(/总评|Sammanfattning/i),
  };
}

